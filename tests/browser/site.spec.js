async function chooseComparison(page,side,id){
 const e=entries.find(e=>e.id===id);
 await page.getByRole('button',{name:side+' 생물 선택 변경',exact:true}).click();
 await page.getByRole('searchbox',{name:side+' 생물 검색',exact:true}).fill(e.latin);
 await page.getByRole('button',{name:'선택: '+e.name,exact:true}).click();
}
